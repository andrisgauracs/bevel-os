def _cells(table, height):
    out = {}
    for code, (first, rows) in table.items():
        width = len(rows[0])
        assert all(len(r) == width for r in rows), "0x%02X: uneven rows" % code
        assert first + len(rows) <= height, "0x%02X: too tall" % code
        out[code] = ["." * width] * first + rows + ["." * width] * (height - first - len(rows))
    return out


